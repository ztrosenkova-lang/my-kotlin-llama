        // Прайс-слова: если в запросе есть и материал/изделие, и цифры-размеры — это прайс
        val priceKeywords = listOf(
            "труба", "труб", "лист", "листов", "уголок", "швеллер", "арматура",
            "профиль", "профнастил", "металл", "сталь", "нержавейка",
