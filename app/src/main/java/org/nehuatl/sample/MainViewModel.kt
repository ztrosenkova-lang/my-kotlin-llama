        private fun determineCategory(text: String): String {
        val lowerText = text.lowercase()

        val hasPrice = Regex("\\d+[.,]?\\d*\\s*(р|руб|₽)").containsMatchIn(lowerText) ||
                lowerText.contains("р/м") ||
                lowerText.contains("р/кг") ||
