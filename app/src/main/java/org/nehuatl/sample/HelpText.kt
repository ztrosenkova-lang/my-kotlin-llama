        📷 АНАЛИЗ ИЗОБРАЖЕНИЙ И PDF (VISION)

        Локальная модель поддерживает анализ изображений и PDF
        через встроенную vision-модель SmolVLM2-500M. Она
        загружается автоматически при первом запросе.

        ⚠️ РАБОТАЕТ ТОЛЬКО В РЕЖИМАХ LOCAL И CLOUD.
        В NEUTRAL появится предупреждение.

        КАК ОТПРАВИТЬ КАРТИНКУ:
        • Кнопка «+» слева от поля ввода.
        • В открывшемся окне — «Галерея» (выбрать фото из памяти)
          или «Камера» (сфотографировать прямо сейчас).
        • Фото автоматически конвертируется в JPEG (поддерживаются
          HEIC/HEIF, WebP, PNG и другие форматы) и отправляется
          в модель.

        КАК ОТПРАВИТЬ PDF:
        • Кнопка «+» → «PDF».
        • Откроется диалог выбора страниц:
            «Первую страницу»   — отправить только первую.
            «Первые 3 страницы» — отправить первые три по очереди
                                  (вторая и третья уйдут только после
                                  того, как vision закончит предыдущую).
            «Номер страницы»    — отправить конкретную страницу.
        • PDF рендерится через Pdfium (движок Chrome) — открывает
          практически любые PDF, которые не тянет нативный движок.

        ⚠️ В CLOUD-режиме описание картинки/PDF делает ЛОКАЛЬНАЯ
        vision-модель (облако не принимает изображения). После
        описания в чат придёт предупреждение «дальше вопросы пойдут
        в облако». Следующий текстовый запрос уйдёт в облако.

        ЧТО ПРОИСХОДИТ:
        • Если текстовая модель уже загружена — она выгружается
          из памяти, загружается vision-модель.
        • После ответа при следующем текстовом сообщении
          vision выгружается, и текстовая модель возвращается.
        • В статус-баре и на поясе робота отображаются этапы:
          «Выгружаю текстовую модель...», «Загружаю зрение...»,
          «Зрение готово — анализирую...», «Возвращаю текстовую модель...».

        ⚠️ ВИДЕО НЕ ПОДДЕРЖИВАЕТСЯ. Приложение работает только
        с фото и PDF.


