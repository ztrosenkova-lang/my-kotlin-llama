        не умеет сжимать диалоги.


        📷 АНАЛИЗ ИЗОБРАЖЕНИЙ И PDF (VISION)

        Локальная модель поддерживает анализ
        изображений и PDF через встроенную
        vision-модель SmolVLM2-500M. Она
        загружается автоматически при первом
        запросе.

        ⚠️ РАБОТАЕТ ТОЛЬКО В РЕЖИМАХ LOCAL
        И CLOUD. В NEUTRAL появится
        предупреждение.

        КАК ОТПРАВИТЬ КАРТИНКУ:
        • Кнопка «+» слева от поля ввода.
        • В открывшемся окне — «Галерея»
          (выбрать фото из памяти) или
          «Камера» (сфотографировать сейчас).
        • Фото автоматически конвертируется
          в JPEG (поддерживаются HEIC/HEIF,
          WebP, PNG и другие форматы)
          и отправляется в модель.

        КАК ОТПРАВИТЬ PDF:
        • Кнопка «+» → «PDF».
        • Откроется диалог выбора страниц:
            «Первую страницу»   — только первую.
            «Первые 3 страницы» — первые три
            по очереди (вторая и третья уйдут только
            после того, как vision закончит предыдущую).
            «Номер страницы»    — конкретную.
        • PDF рендерится через Pdfium (движок
          Chrome) — открывает практически любые
          PDF, которые не тянет нативный движок.

        ⚠️ В CLOUD-режиме описание картинки/PDF
