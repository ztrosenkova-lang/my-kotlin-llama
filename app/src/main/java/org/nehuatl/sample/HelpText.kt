        СПИСОК КНИГ:
        • Поиск по названию и содержанию (Lucene).
        • Нажмите на книгу — откроется читалка.

        TXT-ЧИТАЛКА:
        • Над текстом: «▶ Слушать» / «⏸ Пауза» / «▶ Продолжить»,
          кнопки A−/A+ и поле поиска по содержанию книги.
        • Под текстом: «⬇ Свернуть», «← Назад», «✕ Закрыть».
