        📚 ПАМЯТЬ (ТРИ УРОВНЯ)

        📚 1. База знаний (memory.txt)
        Хранит факты, которые вы явно просите запомнить.
        Команда: «запомни» + текст.
        Пример: запомни цена плитки 1500 рублей за квадратный метр
        ИИ автоматически определяет категорию и сохраняет с датой.

        🧠 2. Долговременная память (brain.txt)
        ИИ автоматически сжимает диалоги каждые 10 сообщений
        и записывает выводы с датой.
        Команда «редактировать мозг» — открыть редактор brain.txt.
        Информация хранится навсегда, ничего не удаляется.

        💬 3. История чата (chat.txt)
        Хранит текущий диалог в постоянном файле chat.txt.
        Читается при запуске приложения — чат восстанавливается.
        Обновляется автоматически при каждом сообщении.
        Команда «редактировать чат» — открыть редактор chat.txt.

        📅 4. Органайзер (organizer.txt)
        Хранит напоминания: дата/время + текст.
        Управляется командой «напомни» и редактором
        «редактировать органайзер». Подробнее — в разделе
        «ОРГАНАЙЗЕР И НАПОМИНАНИЯ».


