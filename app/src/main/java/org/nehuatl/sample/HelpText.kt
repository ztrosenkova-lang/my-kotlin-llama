          позиции, а не с начала.
        • Тап по предложению — начать чтение с него.
        • A−/A+ — размер шрифта (10–20 sp).

        PDF-ЧИТАЛКА:
        • Над текстом: кнопки A−/A+ и процент масштаба.
        • Ручной вертикальный скролл, страницы рендерятся лениво
          (только видимые), кэш на 5 страниц.
        • PDF открываются через Pdfium (движок Chrome) — практически
          любые файлы, включая те, что не открывает нативный движок.

